create table if not exists public.photos (
    id bigint generated by default as identity primary key,
    storage_path text not null unique,
    nickname text not null default 'Convidado',
    caption text not null default '',
    created_at timestamptz not null default now()
);

-- Este protótipo usa a chave service_role SOMENTE no servidor Streamlit.
-- Não coloque essa chave no navegador, em repositórios públicos ou em mensagens.
-- Como a aplicação usa a service_role, as regras RLS não limitam as operações
-- realizadas por ela. Proteja o acesso ao app e os códigos de convidados/admin.
alter table public.photos enable row level security;

